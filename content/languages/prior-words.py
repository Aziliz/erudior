"""Write <course folder>/PRIOR-WORDS.tsv: every word the required (earlier) courses teach.

Writers check it before adding vocabulary, since a later course may not repeat an earlier
course's words (they're carried over automatically, with the learner's progress).
    python3 content/languages/prior-words.py german-b1
"""
import pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent.parent / "math"))
import build  # noqa: E402

folder = next(a / sys.argv[1] for a in build.AREAS if (a / sys.argv[1] / "course.yaml").exists())
meta = build.load_yaml(folder / "course.yaml")
rows = []
for rid in meta.get("requires") or []:
    for v in build.course_vocab(build.folder_for_id(rid)):
        rows.append(f"{v['id']}\t{v['term']}\t{v.get('pos', '')}\t{v['meanings'][0]}\t{v.get('from') or rid}")
(folder / "PRIOR-WORDS.tsv").write_text(
    "# Words taught by earlier courses (id, term, pos, first meaning, course). Generated by prior-words.py; don't edit.\n"
    + "\n".join(rows) + "\n", encoding="utf-8")
print(f"{len(rows)} words -> {folder / 'PRIOR-WORDS.tsv'}")
