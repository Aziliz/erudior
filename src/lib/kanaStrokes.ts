/** ゛ (dakuten) and ゜ (handakuten), drawn at the top right after the base character. */
const DAKUTEN = ["M 80 4 L 86 18", "M 92 2 L 98 16"];
const HANDAKUTEN = ["E 90 10 8 8 -90 270"];

const VOICED: Record<string, [string, "d" | "h"]> = {};
const addVoiced = (base: string, voiced: string, kind: "d" | "h") => {
  [...voiced].forEach((v, i) => (VOICED[v] = [base[i], kind]));
};
addVoiced("かきくけこさしすせそたちつてとはひふへほ", "がぎぐげござじずぜぞだぢづでどばびぶべぼ", "d");
addVoiced("はひふへほ", "ぱぴぷぺぽ", "h");
addVoiced("カキクケコサシスセソタチツテトハヒフヘホウ", "ガギグゲゴザジズゼゾダヂヅデドバビブベボヴ", "d");
addVoiced("ハヒフヘホ", "パピプペポ", "h");

/** Stroke commands for a kana, or undefined if there's no tracing data for it. */
export function kanaStrokes(ch: string): string[] | undefined {
  if (KANA_STROKES[ch]) return KANA_STROKES[ch];
  const v = VOICED[ch];
  if (!v) return undefined;
  const base = KANA_STROKES[v[0]];
  return base && [...base, ...(v[1] === "d" ? DAKUTEN : HANDAKUTEN)];
}

